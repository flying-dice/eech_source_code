void notify_member_task_dependents_completed (entity *member)
{
	entity
		*task,
		*destroy_task;

	task = get_local_entity_first_child (member, LIST_TYPE_TASK_DEPENDENT);

	while (task)
	{
		destroy_task = task;

		task = get_local_entity_child_succ (task, LIST_TYPE_TASK_DEPENDENT);

		if (get_local_entity_type (destroy_task) == ENTITY_TYPE_TASK)
		{
			notify_local_entity (ENTITY_MESSAGE_TASK_COMPLETED, destroy_task, member, TASK_TERMINATED_OBJECTIVE_MESSAGE);
		}
	}
}

