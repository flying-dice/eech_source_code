void increment_group_losses (entity *group)
{
	int
		losses;

	losses = get_local_entity_int_value (group, INT_TYPE_LOSSES);

	losses ++;

	set_local_entity_int_value (group, INT_TYPE_LOSSES, losses);
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void increment_group_primary_task_losses (entity *group)
{
	entity
		*task;

	task = get_local_group_primary_task (group);

	if (task)
	{
		increment_task_losses (task);
	}
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void increment_task_losses (entity *task)
{
	int
		losses;

	ASSERT (task);
	losses = get_local_entity_int_value (task, INT_TYPE_LOSSES);
	set_local_entity_int_value (task, INT_TYPE_LOSSES, losses + 1);
}

