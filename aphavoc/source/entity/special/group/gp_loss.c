void notify_forces_check_campaign_objectives (entity *member)
{
	entity
		*force;

	force = get_local_entity_first_child (get_session_entity (), LIST_TYPE_FORCE);

	while (force)
	{
		notify_local_entity (ENTITY_MESSAGE_CHECK_CAMPAIGN_OBJECTIVES, force, member);

		force = get_local_entity_child_succ (force, LIST_TYPE_FORCE);
	}
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void check_all_force_campaign_objectives (void)
{
	entity
		*force;

	force = get_local_entity_first_child (get_session_entity (), LIST_TYPE_FORCE);
	while (force)
	{
		check_force_campaign_objectives (force);
		force = get_local_entity_child_succ (force, LIST_TYPE_FORCE);
	}
}

