static char default_get_entity_char_value (entity *en, char_types type)
{
	char
		value;

	switch (type)
	{

		case CHAR_TYPE_TAG:

		{
			value = '?';

			break;
		}

		default:

		{
			value = ' ';

			break;
		}
	}

	return (value);
}



























































































































