//
// eech-sys build: compiles the EECH campaign kernel (original C, verbatim
// extracts, patched units and the native host layer in csrc/) for the Cargo
// target, into one static library.
//
// Inputs:
//   EECH_SOURCE_ROOT     the EECH source tree (default: the repository root,
//                        three directories above this crate)
//   EECH_C_OPT           C optimisation level for the kernel (default 0, as the
//                        C reference; see docs/fpu.md before changing it)
//   EECH_ORIGINAL_STACK_ATTRIBUTES=1
//                        build en_creat.c's original va_list reinterpretation
//                        instead of patch P1 (only meaningful on i686, where the
//                        original is correct; refused elsewhere)
//
// Fails loudly when a source, a C compiler or an extraction is missing.
//

#[path = "extract.rs"]
mod extract;
#[path = "patches.rs"]
mod patches;
#[path = "spec.rs"]
mod spec;

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let root = env::var_os("EECH_SOURCE_ROOT").map(PathBuf::from).unwrap_or_else(|| manifest.join("../../..")).canonicalize().expect("EECH_SOURCE_ROOT does not exist");
    assert!(
        root.join("aphavoc/source/entity/system/en_types/en_types.h").exists(),
        "EECH source tree not found at {} (set EECH_SOURCE_ROOT)",
        root.display()
    );
    println!("cargo:rerun-if-env-changed=EECH_SOURCE_ROOT");
    println!("cargo:rerun-if-env-changed=EECH_C_OPT");
    println!("cargo:rerun-if-env-changed=EECH_ORIGINAL_STACK_ATTRIBUTES");
    println!("cargo:rerun-if-changed=build");
    println!("cargo:rerun-if-changed=csrc");

    let out = PathBuf::from(env::var("OUT_DIR").unwrap()).join("eech");
    let gen = out.join("gen");
    fs::create_dir_all(&gen).unwrap();
    let csrc = manifest.join("csrc");

    // 1. generated sources
    let ex = extract::Extractor::new(&root);
    let project_h = format!(
        "{}\n#ifndef EECH_NATIVE_PROJECT_H\n#define EECH_NATIVE_PROJECT_H\n\n{}#endif\n",
        extract::BANNER,
        spec::project_h().iter().map(|s| ex.extract(s)).collect::<Vec<_>>().join("\n")
    );
    write_if_changed(&gen.join("project.h"), &project_h);

    let mut extracted = Vec::new();
    for (name, specs) in spec::extracted_units() {
        let path = gen.join(name);
        write_if_changed(&path, &extract::generate(&ex, &specs));
        extracted.push((name, path));
    }

    // name <-> ordinal tables: member names parsed from the original enums,
    // values supplied by the C compiler (never computed here)
    let mut names = String::from(extract::BANNER);
    names.push_str("#include \"project.h\"\n#include \"eech_kernel_internal.h\"\n\n");
    let mut table_entries = String::new();
    for (table, enum_name, file) in NAME_TABLES {
        let text = ex.read_source(file);
        let re = regex::Regex::new(&format!(r"\nenum {enum_name}\s*\n\{{([^}}]*)\}};")).unwrap();
        let body = re.captures(&text).unwrap_or_else(|| panic!("enum {enum_name} not found in {file}"))[1].to_string();
        let member = regex::Regex::new(r"^\s*([A-Z_][A-Z0-9_]*)\s*(=[^,]*)?,?\s*(//.*)?$").unwrap();
        names.push_str(&format!("static const eech_name_entry names_{table}[] =\n{{\n"));
        for line in body.lines() {
            if let Some(c) = member.captures(line) {
                let m = &c[1];
                if !m.starts_with("NUM_") {
                    names.push_str(&format!("\t{{ \"{m}\", {m} }},\n"));
                }
            }
        }
        names.push_str("\t{ NULL, 0 }\n};\n\n");
        table_entries.push_str(&format!("\t{{ \"{table}\", names_{table} }},\n"));
    }
    names.push_str(&format!("const eech_name_table eech_name_tables[] =\n{{\n{table_entries}\t{{ NULL, NULL }}\n}};\n"));
    let names_path = gen.join("eech_names.c");
    write_if_changed(&names_path, &names);

    // the legacy replay's create lines: one real variadic call per shape of
    // attribute list (0 int, 1 float, 2 vec3d, 3 parent/pred), up to 5 attributes
    let mut inc = String::from("/* GENERATED by eech-sys/build: create_client_server_entity calls by attribute shape */\n");
    for n in 0..=5u32 {
        for shape in 0..4u32.pow(n) {
            let mut args = String::new();
            for i in 0..n {
                let digit = (shape / 4u32.pow(n - 1 - i)) % 4;
                let m = ["A_INT", "A_FLOAT", "A_VEC3D", "A_LINK"][digit as usize];
                args.push_str(&format!("{m} ({i}), "));
            }
            inc.push_str(&format!("if ((n == {n}) && (shape == {shape})) return create_client_server_entity (type, index, {args}entity_attr_end);\n"));
        }
    }
    write_if_changed(&gen.join("eech_legacy_create.inc"), &inc);

    let mut patched = Vec::new();
    for file in spec::PATCHED_UNITS {
        let text = ex.read_source(file);
        let name = Path::new(file).file_name().unwrap().to_str().unwrap();
        let path = gen.join(format!("patched_{name}"));
        write_if_changed(&path, &patches::apply(file, &text));
        patched.push(path);
    }

    // 2. target and flags
    let arch = env::var("CARGO_CFG_TARGET_ARCH").unwrap();
    let pointer_width = env::var("CARGO_CFG_TARGET_POINTER_WIDTH").unwrap();
    let original_attrs = env::var("EECH_ORIGINAL_STACK_ATTRIBUTES").map(|v| v == "1").unwrap_or(false);
    if original_attrs && !(arch == "x86" && pointer_width == "32") {
        panic!("EECH_ORIGINAL_STACK_ATTRIBUTES=1 builds en_creat.c's i386-only va_list reinterpretation; refusing for {arch}/{pointer_width}-bit");
    }
    let opt = env::var("EECH_C_OPT").unwrap_or_else(|_| "0".into());

    let base = || {
        let mut b = cc::Build::new();
        b.opt_level_str(&opt)
            .debug(true)
            .include(&gen)
            .include(&csrc)
            .include(root.join("aphavoc/source"))
            .include(root.join("modules"))
            .flag_if_supported("-std=gnu99")
            .flag_if_supported("-ffp-contract=off")
            .flag_if_supported("-fno-fast-math")
            .warnings(false)
            .cargo_warnings(false);
        if arch == "x86" {
            // C float arithmetic at declared type (FLT_EVAL_METHOD 0), as the C reference
            b.flag("-msse2").flag("-mfpmath=sse");
        }
        if original_attrs {
            b.define("EECH_ORIGINAL_STACK_ATTRIBUTES", "1");
        }
        b
    };

    // original code: its historical warnings are not ours, but mismatches with
    // the environment and pointer-width conversions are errors
    let original_flags = [
        "-Werror=implicit-function-declaration",
        "-Werror=incompatible-pointer-types",
        "-Werror=int-conversion",
        "-Werror=return-type",
        "-Werror=pointer-to-int-cast",
        "-Werror=int-to-pointer-cast",
    ];

    let mut objects: Vec<PathBuf> = Vec::new();

    // original units compiled unchanged (with their controlled definitions)
    for unit in spec::REAL_TRANSLATION_UNITS {
        let mut b = base();
        for f in original_flags {
            b.flag(f);
        }
        for (u, defs) in spec::UNIT_DEFINES {
            if u == unit {
                for d in *defs {
                    let (k, v) = d.split_once('=').unwrap();
                    b.define(k, v);
                }
            }
        }
        b.file(root.join(unit));
        objects.extend(b.compile_intermediates());
    }
    // verbatim extracts and patched units
    for (name, path) in &extracted {
        let mut b = base();
        for f in original_flags {
            b.flag(f);
        }
        if spec::ZERO_INIT_UNITS.contains(name) {
            b.flag("-ftrivial-auto-var-init=zero");
        }
        b.file(path);
        objects.extend(b.compile_intermediates());
    }
    for path in &patched {
        let mut b = base();
        for f in original_flags {
            b.flag(f);
        }
        b.file(path);
        objects.extend(b.compile_intermediates());
    }
    // the native host layer (ours): every warning is an error
    {
        let mut b = base();
        b.flag("-Wall").flag("-Werror").flag("-Wno-unused-function").flag("-Wno-unused-variable");
        b.file(&names_path);
        for entry in fs::read_dir(&csrc).unwrap() {
            let p = entry.unwrap().path();
            if p.extension().is_some_and(|e| e == "c") {
                b.file(p);
            }
        }
        objects.extend(b.compile_intermediates());
    }

    // one archive: the kernel's objects resolve each other in any order
    let lib = out.join("libeech_kernel.a");
    let _ = fs::remove_file(&lib);
    let mut ar = base().get_archiver();
    ar.arg("crs").arg(&lib).args(&objects);
    run(&mut ar, "archive the EECH kernel");
    println!("cargo:rustc-link-search=native={}", out.display());
    println!("cargo:rustc-link-lib=static=eech_kernel");
    if env::var("CARGO_CFG_TARGET_OS").unwrap() != "windows" {
        println!("cargo:rustc-link-lib=m");
    }

    // 3. the source closure: every original file the kernel is built from
    let compiler = base().get_compiler();
    let mut closure: std::collections::BTreeSet<String> = ex.read.borrow().clone();
    for unit in spec::REAL_TRANSLATION_UNITS {
        closure.insert(unit.to_string());
    }
    let mut dep_inputs: Vec<PathBuf> = spec::REAL_TRANSLATION_UNITS.iter().map(|u| root.join(u)).collect();
    dep_inputs.extend(extracted.iter().map(|(_, p)| p.clone()));
    dep_inputs.extend(patched.iter().cloned());
    if !compiler.is_like_msvc() {
        for input in &dep_inputs {
            let mut cmd = compiler.to_command();
            cmd.arg("-M").arg(input);
            let output = cmd.output().expect("run the C compiler for the dependency scan");
            assert!(output.status.success(), "dependency scan failed for {}: {}", input.display(), String::from_utf8_lossy(&output.stderr));
            let text = String::from_utf8_lossy(&output.stdout).replace("\\\n", " ");
            for dep in text.split_whitespace().skip(1) {
                if let Ok(canon) = Path::new(dep).canonicalize() {
                    if let Ok(rel) = canon.strip_prefix(&root) {
                        closure.insert(rel.to_string_lossy().replace('\\', "/"));
                    }
                }
            }
        }
    }
    for file in &closure {
        println!("cargo:rerun-if-changed={}", root.join(file).display());
    }
    let mut report = String::from("# EECH source closure of the native kernel (generated by eech-sys/build)\n");
    report.push_str(&format!("# target {arch} {pointer_width}-bit, C opt {opt}, compiler {}\n", compiler.path().display()));
    for f in &closure {
        report.push_str(f);
        report.push('\n');
    }
    write_if_changed(&out.join("closure.txt"), &report);
    println!("cargo:rustc-env=EECH_CLOSURE_REPORT={}", out.join("closure.txt").display());
    println!("cargo:rustc-env=EECH_C_OPT_LEVEL={opt}");
    println!("cargo:rustc-env=EECH_C_COMPILER={}", compiler.path().display());
    println!("cargo:rustc-env=EECH_ORIGINAL_STACK_ATTRIBUTES_BUILD={}", u8::from(original_attrs));
    println!("cargo:rustc-env=EECH_KERNEL_OBJECTS={}", objects.iter().map(|p| p.display().to_string()).collect::<Vec<_>>().join(if cfg!(windows) { ";" } else { ":" }));
}

