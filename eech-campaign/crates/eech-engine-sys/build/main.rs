//
// eech-engine-sys build: compiles ALL of EECH headless for the Cargo target.
//
// The source list (sources.txt) is the maintained Windows build's: every .c
// file of the aphavoc and modules Visual Studio projects, minus the eight
// platform backends that csrc/ replaces (WinMain and the window, the debug
// windows, DirectInput joysticks, GDI fonts, DirectDraw, the Direct3D device,
// DirectPlay and its GUIDs). The WIN32 code path is compiled against the
// compat/ headers (the Windows SDK and DirectX names EECH uses).
//
// The original tree is staged into OUT_DIR, where patches.rs is applied; the
// source tree itself is never modified.
//
// Targets: x86_64 Linux, and x86_64 Windows with MinGW-w64 (windows-gnu).
// On Windows the Win32 names csrc/ implements are renamed eech_w32_*
// (csrc/eech_win32_names.h, force-included), so that EECH keeps its Linux
// emulation and the rest of the process keeps the system DLLs.
//
// Inputs:
//   EECH_SOURCE_ROOT   the EECH source tree (default: the repository root)
//   EECH_ENGINE_OPT    C optimisation level (default 1)
//

#[path = "patches.rs"]
mod patches;

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

const REPLACED: &[&str] = &[
    "modules/system/startup.c",
    "modules/system/debug.c",
    "modules/system/joystick.c",
    "modules/userint2/ui_draw/uifont.c",
    "modules/graphics/dirdraw.c",
    "modules/graphics/f3d.c",
    "modules/multi/directp.c",
    "modules/multi/dpguid.c",
];

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let root = env::var_os("EECH_SOURCE_ROOT")
        .map(PathBuf::from)
        .unwrap_or_else(|| manifest.join("../../.."))
        .canonicalize()
        .expect("EECH_SOURCE_ROOT does not exist");
    assert!(root.join("aphavoc/source/project.h").exists(), "EECH source tree not found at {} (set EECH_SOURCE_ROOT)", root.display());
    println!("cargo:rerun-if-env-changed=EECH_SOURCE_ROOT");
    println!("cargo:rerun-if-env-changed=EECH_ENGINE_OPT");
    println!("cargo:rerun-if-changed=build");
    println!("cargo:rerun-if-changed=compat");
    println!("cargo:rerun-if-changed=csrc");
    println!("cargo:rerun-if-changed=sources.txt");

    let target_os = env::var("CARGO_CFG_TARGET_OS").unwrap();
    let target_env = env::var("CARGO_CFG_TARGET_ENV").unwrap_or_default();
    let windows = target_os == "windows";
    assert!(
        target_os == "linux" || (windows && target_env == "gnu"),
        "eech-engine-sys: builds for Linux, and for Windows with MinGW-w64 (x86_64-pc-windows-gnu); not {target_os}/{target_env}"
    );

    let sources: Vec<String> = fs::read_to_string(manifest.join("sources.txt"))
        .unwrap()
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .map(String::from)
        .collect();
    for r in REPLACED {
        assert!(!sources.iter().any(|s| s == r), "{r} is replaced by csrc/ and must not be in sources.txt");
    }

    // 1. stage the original tree (only what the compiler reads), then apply the patches
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let tree = out.join("tree");
    for dir in ["modules", "aphavoc/source"] {
        stage(&root.join(dir), &tree.join(dir));
    }
    for file in patches::patched_files() {
        let original = fs::read(root.join(file)).unwrap_or_else(|e| panic!("{file}: {e}"));
        // the sources are Latin-1: patch bytes as chars 0..=255
        let text: String = original.iter().map(|&b| b as char).collect();
        let patched: Vec<u8> = patches::apply(file, &text).chars().map(|c| c as u32 as u8).collect();
        write_if_changed(&tree.join(file), &patched);
    }

    // 2. generated sources: the system texture names (textname.h's enum members
    //    without their TEXTURE_INDEX_ prefix), which textures.bin lists
    let gen = out.join("gen");
    let texture_names = texture_names(&tree.join("modules/3d/textname.h"));
    let mut c = String::from("/* generated by eech-engine-sys build.rs from modules/3d/textname.h */\n\nconst char *const eech_texture_names[] =\n{\n");
    for n in &texture_names {
        c.push_str(&format!("\t\"{n}\",\n"));
    }
    c.push_str(&format!("}};\n\nconst int eech_number_of_texture_names = {};\n", texture_names.len()));
    write_if_changed(&gen.join("eech_texture_names.c"), c.as_bytes());

    // 3. compile
    let opt = env::var("EECH_ENGINE_OPT").unwrap_or_else(|_| "1".into());
    let mut build = cc::Build::new();
    build
        .include(manifest.join("compat"))
        .include(manifest.join("csrc"))
        .include(tree.join("modules"))
        .include(tree.join("aphavoc/source"))
        .define("WIN32", None)
        .opt_level_str(&opt)
        .debug(true)
        .pic(true)
        .warnings(false)
        .flag("-std=gnu99")
        .flag("-w")
        // tentative definitions in headers, as MSVC links them
        .flag("-fcommon")
        .flag("-fno-strict-aliasing")
        .flag("-fwrapv")
        // F1 (docs/patches.md): locals EECH reads before writing are zero, as in the C reference
        .flag("-ftrivial-auto-var-init=zero")
        // the 64-bit hazards that must not pass silently
        .flag("-Werror=implicit-function-declaration")
        .flag("-Werror=implicit-int")
        .flag("-Werror=int-conversion");
    if windows {
        build.flag("-include").flag(manifest.join("csrc/eech_win32_names.h").to_str().unwrap());
    }
    // EECH_ENGINE_SANITIZE=address: an AddressSanitizer build (Linux; run with the
    // runtime preloaded: LD_PRELOAD=$(cc -print-file-name=libasan.so))
    println!("cargo:rerun-if-env-changed=EECH_ENGINE_SANITIZE");
    if let Ok(sanitizer) = env::var("EECH_ENGINE_SANITIZE") {
        build.flag(&format!("-fsanitize={sanitizer}")).flag(&format!("-fsanitize-recover={sanitizer}"));
        println!("cargo:rustc-link-lib=dylib=asan");
    }
    for s in &sources {
        build.file(tree.join(s));
    }
    for entry in fs::read_dir(manifest.join("csrc")).unwrap() {
        let path = entry.unwrap().path();
        if path.extension().is_some_and(|e| e == "c") {
            build.file(path);
        }
    }
    build.file(gen.join("eech_texture_names.c"));
    build.compile("eech_engine");
    if windows {
        // winpthreads, linked statically: the DLL needs no MinGW runtime beside it
        let compiler = cc::Build::new().get_compiler();
        let out = std::process::Command::new(compiler.path()).arg("-print-file-name=libwinpthread.a").output().expect("the MinGW-w64 C compiler");
        let lib = PathBuf::from(String::from_utf8_lossy(&out.stdout).trim());
        assert!(lib.is_absolute(), "libwinpthread.a not found by {}", compiler.path().display());
        println!("cargo:rustc-link-search=native={}", lib.parent().unwrap().display());
        println!("cargo:rustc-link-lib=static=winpthread");
    } else {
        println!("cargo:rustc-link-lib=m");
        println!("cargo:rustc-link-lib=pthread");
    }
    println!("cargo:root={}", tree.display());
}

/// the members of enum TEXTURE_INDEX_NUMBERS up to TEXTURE_INDEX_LAST_DEFAULT_INDEX's value
fn texture_names(header: &Path) -> Vec<String> {
    let bytes = fs::read(header).unwrap_or_else(|e| panic!("{}: {e}", header.display()));
    let text: String = bytes.iter().map(|&b| b as char).collect();
    let start = text.find("enum TEXTURE_INDEX_NUMBERS").expect("textname.h: enum TEXTURE_INDEX_NUMBERS");
    let body = &text[start..];
    let body = &body[..body.find("};").expect("textname.h: end of enum")];
    // strip comments
    let mut clean = String::new();
    let mut rest = body;
    while let Some(i) = rest.find("/*") {
        clean.push_str(&rest[..i]);
        rest = &rest[i + 2..];
        rest = &rest[rest.find("*/").map(|j| j + 2).unwrap_or(rest.len())..];
    }
    clean.push_str(rest);
    let clean: String = clean.lines().map(|l| l.split("//").next().unwrap_or("")).collect::<Vec<_>>().join("\n");
    let mut names = Vec::new();
    let mut last_default = None;
    for item in clean.split(',') {
        let item = item.trim();
        let Some(pos) = item.find("TEXTURE_INDEX_") else { continue };
        let item = &item[pos..];
        if let Some((name, value)) = item.split_once('=') {
            if name.trim() == "TEXTURE_INDEX_LAST_DEFAULT_INDEX" {
                last_default = Some(value.trim().to_string());
            }
            continue;
        }
        let name: String = item.chars().take_while(|c| c.is_ascii_alphanumeric() || *c == '_').collect();
        names.push(name);
    }
    let last = last_default.expect("textname.h: TEXTURE_INDEX_LAST_DEFAULT_INDEX");
    let end = names.iter().position(|n| *n == last).expect("textname.h: the last default texture") + 1;
    names.truncate(end);
    names.into_iter().map(|n| n.trim_start_matches("TEXTURE_INDEX_").to_string()).collect()
}

fn stage(from: &Path, to: &Path) {
    for entry in fs::read_dir(from).unwrap_or_else(|e| panic!("{}: {e}", from.display())) {
        let entry = entry.unwrap();
        let path = entry.path();
        let target = to.join(entry.file_name());
        if entry.file_type().unwrap().is_dir() {
            stage(&path, &target);
        } else if path.extension().and_then(|e| e.to_str()).is_some_and(|e| matches!(e.to_ascii_lowercase().as_str(), "c" | "h" | "inl")) {
            write_if_changed(&target, &fs::read(&path).unwrap());
        }
    }
}

fn write_if_changed(path: &Path, bytes: &[u8]) {
    if fs::read(path).ok().as_deref() != Some(bytes) {
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, bytes).unwrap();
    }
}
