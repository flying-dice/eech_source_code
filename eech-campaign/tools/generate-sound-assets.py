#!/usr/bin/env python3
"""Regenerates crates/eech-world/src/sound_assets.rs: the reference host's own table of sample asset names and their rates (EEDCS-51, D3).

The reference host owns the physical sample metadata (rate, original rate, header lookup). Its rates are the data of the sample files EECH ships; the only machine-readable copy of them is the
descriptor table of aphavoc/source/appsound/snd_data.c, so this tool reads (name, rate) from that table, once, and the host keeps them as its own data. The campaign no longer reads the table's rate
for its initialisation. A test of the host (crates/eech-world/src/sound_data.rs) parses the same table again and fails when the generated file and the table disagree on any name or rate.

usage: tools/generate-sound-assets.py [--check]      (writes the file; --check only compares it)
"""
import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / 'aphavoc/source/appsound/snd_data.c'
TARGET = REPO / 'eech-campaign/crates/eech-world/src/sound_assets.rs'


def strip_comments(text):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    return re.sub(r'//[^\n]*', '', text)


def unescape(literal):
    """A C string literal's contents; the table uses only the escaped backslash."""
    out, i = [], 0
    while i < len(literal):
        ch = literal[i]
        if ch == '\\':
            assert literal[i + 1] == '\\', 'an escape other than \\\\ in ' + literal
            out.append('\\')
            i += 2
        else:
            out.append(ch)
            i += 1
    return ''.join(out)


def table():
    text = strip_comments(SOURCE.read_text(encoding='latin-1'))
    start = text.index('application_sound_samples[]')
    end = text.index('};', start)
    found = {}
    for m in re.finditer(r'\{\s*SOUND_SAMPLE_INDEX_[A-Z0-9_]+\s*,\s*ENTITY_SIDE_[A-Z_]+\s*,\s*"((?:[^"\\]|\\.)*)"\s*,\s*(\d+)\s*,', text[start:end]):
        name, rate = unescape(m.group(1)), int(m.group(2))
        assert name.isascii() and name
        assert found.setdefault(name, rate) == rate, 'one asset name with two rates: ' + name
    return sorted(found.items(), key=lambda item: item[0].encode('ascii'))


def render(entries):
    lines = [
        '//! GENERATED by tools/generate-sound-assets.py from the descriptor table of aphavoc/source/appsound/snd_data.c; do not edit by hand (EEDCS-51, D3).',
        '//!',
        "//! The reference host's own table of sample asset names and their rates in hertz, sorted by name (byte order) for a binary search. The campaign names an asset and the host answers its rate; the",
        "//! campaign no longer supplies it. A test in `sound_data.rs` parses the descriptor table again and fails when this file and the table disagree.",
        '',
        'pub const SAMPLE_RATES: &[(&str, i32)] = &[',
    ]
    for name, rate in entries:
        lines.append('    ("%s", %d),' % (name.replace('\\', '\\\\'), rate))
    lines.append('];')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = render(table())
    if args.check:
        same = TARGET.exists() and TARGET.read_text(encoding='utf-8') == text
        print('sound_assets.rs is ' + ('current' if same else 'STALE'))
        return 0 if same else 1
    with TARGET.open('w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote %s (%d assets)' % (TARGET, text.count('\n    (')))
    return 0


if __name__ == '__main__':
    sys.exit(main())
